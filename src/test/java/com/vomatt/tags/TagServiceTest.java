@ExtendWith(MockitoExtension.class)
@DisplayName("TagService")
class TagServiceTest {

    @Mock
    TagRepository tagRepository;

    @Mock
    UserRepository userRepository;

    @InjectMocks
    TagService tagService;

    // ─── helper ───────────────────────────────────────────────────────────────

    private static Tag withId(Tag tag, UUID id) {
        ReflectionTestUtils.setField(tag, "id", id);
        return tag;
    }

    private static Tag createTagWithId(String name, String slug, String description, int displayOrder) {
        return withId(new Tag(name, slug, description, displayOrder), UUID.randomUUID());
    }

    private static void assertApiException(Throwable ex, HttpStatus status, MessageKey key) {
        assertThat(ex).isInstanceOf(ApiException.class);
        ApiException apiEx = (ApiException) ex;
        assertThat(apiEx.getStatus()).isEqualTo(status);
        assertThat(apiEx.getMessageKey()).isEqualTo(key);
    }

    // ─── createTag ────────────────────────────────────────────────────────────

    @Nested
    @DisplayName("createTag")
    class CreateTagTests {

        @Test
        @DisplayName("should generate slug when slug is not provided (Tech News -> tech-news)")
        void shouldCreateTagWithAutoGeneratedSlug() {
            CreateTagRequest request = new CreateTagRequest();
            request.setName("Tech News");
            request.setDescription("Technology news");
            request.setDisplayOrder(1);

            when(tagRepository.existsByName("Tech News")).thenReturn(false);
            when(tagRepository.existsBySlug("tech-news")).thenReturn(false);
            when(tagRepository.save(any(Tag.class))).thenAnswer(inv -> withId(inv.getArgument(0), UUID.randomUUID()));

            TagDto result = tagService.createTag(request);

            assertThat(result).isNotNull();
            assertThat(result.getName()).isEqualTo("Tech News");
            assertThat(result.getSlug()).isEqualTo("tech-news");
            assertThat(result.getDescription()).isEqualTo("Technology news");
            assertThat(result.getDisplayOrder()).isEqualTo(1);
            assertThat(result.getUsageCount()).isEqualTo(0);
            assertThat(result.getId()).isNotNull();
        }

        @Test
        @DisplayName("should use slug as-is when provided (food stays food)")
        void shouldUseProvidedSlug() {
            CreateTagRequest request = new CreateTagRequest();
            request.setName("Food");
            request.setSlug("food");
            request.setDisplayOrder(0);

            when(tagRepository.existsByName("Food")).thenReturn(false);
            when(tagRepository.existsBySlug("food")).thenReturn(false);
            when(tagRepository.save(any(Tag.class))).thenAnswer(inv -> withId(inv.getArgument(0), UUID.randomUUID()));

            TagDto result = tagService.createTag(request);

            assertThat(result.getSlug()).isEqualTo("food");
            verify(tagRepository).existsBySlug("food");
        }

        @Test
        @DisplayName("should throw 409 TAG_NAME_EXISTS when name is duplicated")
        void shouldThrowWhenNameDuplicate() {
            CreateTagRequest request = new CreateTagRequest();
            request.setName("Tech");

            when(tagRepository.existsByName("Tech")).thenReturn(true);

            assertThatThrownBy(() -> tagService.createTag(request))
                    .satisfies(ex -> assertApiException(ex, HttpStatus.CONFLICT, MessageKey.TAG_NAME_EXISTS));

            verify(tagRepository, never()).save(any());
        }

        @Test
        @DisplayName("should throw 409 TAG_SLUG_EXISTS when slug is duplicated")
        void shouldThrowWhenSlugDuplicate() {
            CreateTagRequest request = new CreateTagRequest();
            request.setName("Tech");
            request.setSlug("tech");

            when(tagRepository.existsByName("Tech")).thenReturn(false);
            when(tagRepository.existsBySlug("tech")).thenReturn(true);

            assertThatThrownBy(() -> tagService.createTag(request))
                    .satisfies(ex -> assertApiException(ex, HttpStatus.CONFLICT, MessageKey.TAG_SLUG_EXISTS));

            verify(tagRepository, never()).save(any());
        }
    }

    // ─── updateTag ────────────────────────────────────────────────────────────

    @Nested
    @DisplayName("updateTag")
    class UpdateTagTests {

        @Test
        @DisplayName("should update tag fields and save")
        void shouldUpdateTag() {
            UUID tagId = UUID.randomUUID();
            Tag existing = withId(new Tag("OldName", "old-name", "Old desc", 0), tagId);

            UpdateTagRequest request = new UpdateTagRequest();
            request.setName("NewName");
            request.setSlug("new-name");
            request.setDescription("New desc");
            request.setDisplayOrder(5);

            when(tagRepository.findById(tagId)).thenReturn(Optional.of(existing));
            when(tagRepository.existsByNameAndIdNot("NewName", tagId)).thenReturn(false);
            when(tagRepository.existsBySlugAndIdNot("new-name", tagId)).thenReturn(false);
            when(tagRepository.save(any(Tag.class))).thenReturn(existing);

            TagDto result = tagService.updateTag(tagId.toString(), request);

            assertThat(result.getName()).isEqualTo("NewName");
            assertThat(result.getSlug()).isEqualTo("new-name");
            assertThat(result.getDescription()).isEqualTo("New desc");
            assertThat(result.getDisplayOrder()).isEqualTo(5);
            verify(tagRepository).save(existing);
        }

        @Test
        @DisplayName("should throw 404 TAG_NOT_FOUND when tag is not found")
        void shouldThrowWhenTagNotFound() {
            UUID tagId = UUID.randomUUID();
            when(tagRepository.findById(tagId)).thenReturn(Optional.empty());

            UpdateTagRequest request = new UpdateTagRequest();
            request.setName("AnyName");
            request.setDisplayOrder(0);

            assertThatThrownBy(() -> tagService.updateTag(tagId.toString(), request))
                    .satisfies(ex -> assertApiException(ex, HttpStatus.NOT_FOUND, MessageKey.TAG_NOT_FOUND));
        }

        @Test
        @DisplayName("should throw 409 TAG_NAME_EXISTS when updated name conflicts")
        void shouldThrowWhenUpdatedNameConflicts() {
            UUID tagId = UUID.randomUUID();
            Tag existing = withId(new Tag("OldName", "old-name", null, 0), tagId);

            UpdateTagRequest request = new UpdateTagRequest();
            request.setName("ConflictName");
            request.setDisplayOrder(0);

            when(tagRepository.findById(tagId)).thenReturn(Optional.of(existing));
            when(tagRepository.existsByNameAndIdNot("ConflictName", tagId)).thenReturn(true);

            assertThatThrownBy(() -> tagService.updateTag(tagId.toString(), request))
                    .satisfies(ex -> assertApiException(ex, HttpStatus.CONFLICT, MessageKey.TAG_NAME_EXISTS));

            verify(tagRepository, never()).save(any());
        }

        @Test
        @DisplayName("should throw 409 TAG_SLUG_EXISTS when updated slug conflicts")
        void shouldThrowWhenUpdatedSlugConflicts() {
            UUID tagId = UUID.randomUUID();
            Tag existing = withId(new Tag("OldName", "old-name", null, 0), tagId);

            UpdateTagRequest request = new UpdateTagRequest();
            request.setName("NewName");
            request.setSlug("conflict-slug");
            request.setDisplayOrder(0);

            when(tagRepository.findById(tagId)).thenReturn(Optional.of(existing));
            when(tagRepository.existsByNameAndIdNot("NewName", tagId)).thenReturn(false);
            when(tagRepository.existsBySlugAndIdNot("conflict-slug", tagId)).thenReturn(true);

            assertThatThrownBy(() -> tagService.updateTag(tagId.toString(), request))
                    .satisfies(ex -> assertApiException(ex, HttpStatus.CONFLICT, MessageKey.TAG_SLUG_EXISTS));

            verify(tagRepository, never()).save(any());
        }
    }

    // ─── deleteTag ────────────────────────────────────────────────────────────

    @Nested
    @DisplayName("deleteTag")
    class DeleteTagTests {

        @Test
        @DisplayName("should delete tag when no Poll references it")
        void shouldDeleteUnreferencedTag() {
            UUID tagId = UUID.randomUUID();
            Tag tag = withId(new Tag("Tech", "tech", null, 0), tagId);

            when(tagRepository.findById(tagId)).thenReturn(Optional.of(tag));
            when(tagRepository.isTagReferencedByVotes(tagId)).thenReturn(false);

            tagService.deleteTag(tagId.toString());

            verify(tagRepository).delete(tag);
        }

        @Test
        @DisplayName("should throw 409 TAG_IN_USE when a Poll references the tag")
        void shouldThrowConflictWhenTagIsReferenced() {
            UUID tagId = UUID.randomUUID();
            Tag tag = withId(new Tag("Tech", "tech", null, 0), tagId);

            when(tagRepository.findById(tagId)).thenReturn(Optional.of(tag));
            when(tagRepository.isTagReferencedByVotes(tagId)).thenReturn(true);

            assertThatThrownBy(() -> tagService.deleteTag(tagId.toString()))
                    .satisfies(ex -> assertApiException(ex, HttpStatus.CONFLICT, MessageKey.TAG_IN_USE));

            verify(tagRepository, never()).delete(any());
        }

        @Test
        @DisplayName("should throw 404 TAG_NOT_FOUND when tag is not found")
        void shouldThrowWhenTagNotFoundOnDelete() {
            UUID tagId = UUID.randomUUID();
            when(tagRepository.findById(tagId)).thenReturn(Optional.empty());

            assertThatThrownBy(() -> tagService.deleteTag(tagId.toString()))
                    .satisfies(ex -> assertApiException(ex, HttpStatus.NOT_FOUND, MessageKey.TAG_NOT_FOUND));
        }
    }

    // ─── getAllTags ───────────────────────────────────────────────────────────

    @Nested
    @DisplayName("getAllTags")
    class GetAllTagsTests {

        @Test
        @DisplayName("should return all tags sorted by displayOrder")
        void shouldReturnAllTagsOrderedByDisplayOrder() {
            Tag tag1 = createTagWithId("Alpha", "alpha", null, 1);
            Tag tag2 = createTagWithId("Beta", "beta", null, 2);
            Tag tag3 = createTagWithId("Gamma", "gamma", null, 3);

            when(tagRepository.findAllByOrderByDisplayOrderAsc()).thenReturn(List.of(tag1, tag2, tag3));

            List<TagDto> result = tagService.getAllTags();

            assertThat(result).hasSize(3);
            assertThat(result.get(0).getName()).isEqualTo("Alpha");
            assertThat(result.get(1).getName()).isEqualTo("Beta");
            assertThat(result.get(2).getName()).isEqualTo("Gamma");
        }
    }

    // ─── getPopularTags ───────────────────────────────────────────────────────

    @Nested
    @DisplayName("getPopularTags")
    class GetPopularTagsTests {

        @Test
        @DisplayName("should return popular tags by usageCount and give next-page cursor when there is one more row")
        void shouldReturnTagsOrderedByUsageCount() {
            Tag tag1 = createTagWithId("Popular", "popular", null, 0);
            tag1.setUsageCount(100);
            Tag tag2 = createTagWithId("LessPopular", "less-popular", null, 0);
            tag2.setUsageCount(50);
            Tag tag3 = createTagWithId("Rare", "rare", null, 0);
            tag3.setUsageCount(1);
            when(tagRepository.findPopularPage(null, null, org.springframework.data.domain.Limit.of(3)))
                    .thenReturn(List.of(tag1, tag2, tag3));

            CursorResponse<TagDto> result = tagService.getPopularTags(null, 2);

            assertThat(result.items()).extracting(TagDto::getName).containsExactly("Popular", "LessPopular");
            Cursor next = Cursor.decode(result.nextCursor(), Cursor.Scope.POPULAR_TAGS);
            assertThat(next.longKey()).isEqualTo(50);
            assertThat(next.id()).isEqualTo(tag2.getId());
        }
    }

    // ─── followTag / unfollowTag ──────────────────────────────────────────────

    @Nested
    @DisplayName("followTag / unfollowTag")
    class FollowTagTests {

        final UUID userId = UUID.randomUUID();

        @Test
        @DisplayName("should follow an existing tag")
        void shouldFollowWhenTagExists() {
            UUID tagId = UUID.randomUUID();
            when(tagRepository.follow(userId, tagId)).thenReturn(1);

            tagService.followTag(userId.toString(), tagId.toString());

            verify(tagRepository, never()).existsById(any());
        }

        @Test
        @DisplayName("should succeed when the tag is already followed")
        void shouldSucceedWhenTagAlreadyFollowed() {
            UUID tagId = UUID.randomUUID();
            when(tagRepository.follow(userId, tagId)).thenReturn(0);
            when(tagRepository.existsById(tagId)).thenReturn(true);

            tagService.followTag(userId.toString(), tagId.toString());
        }

        @Test
        @DisplayName("should throw 404 user.not_found when the signed-in user no longer exists")
        void shouldThrowUserNotFoundWhenFollowerIsGone() {
            UUID tagId = UUID.randomUUID();
            when(tagRepository.follow(userId, tagId)).thenReturn(0);
            doCallRealMethod().when(userRepository).requireExists(userId);
            when(userRepository.existsById(userId)).thenReturn(false);

            assertThatThrownBy(() -> tagService.followTag(userId.toString(), tagId.toString()))
                    .satisfies(ex -> assertApiException(ex, HttpStatus.NOT_FOUND, MessageKey.USER_NOT_FOUND));
            verify(tagRepository, never()).existsById(any());
        }

        @Test
        @DisplayName("should throw 404 when following an unknown tag")
        void shouldThrowNotFoundWhenFollowingUnknownTag() {
            UUID tagId = UUID.randomUUID();
            when(tagRepository.follow(userId, tagId)).thenReturn(0);
            when(tagRepository.existsById(tagId)).thenReturn(false);

            assertThatThrownBy(() -> tagService.followTag(userId.toString(), tagId.toString()))
                    .satisfies(ex -> assertApiException(ex, HttpStatus.NOT_FOUND, MessageKey.TAG_NOT_FOUND));
        }

        @Test
        @DisplayName("should unfollow without looking the tag up")
        void shouldUnfollowWhenTagUnknown() {
            UUID tagId = UUID.randomUUID();

            tagService.unfollowTag(userId.toString(), tagId.toString());

            verify(tagRepository).unfollow(userId, tagId);
            verify(tagRepository, never()).findById(any());
        }

        @Test
        @DisplayName("should list the followed tags")
        void shouldListFollowedTagsWhenUserFollowsTags() {
            Tag tag = createTagWithId("Tech", "tech", null, 1);
            when(tagRepository.findFollowedBy(userId)).thenReturn(List.of(tag));

            assertThat(tagService.getFollowedTags(userId.toString())).extracting(TagDto::getSlug).containsExactly("tech");
        }
    }
}
